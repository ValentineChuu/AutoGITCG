"""The fixed benchmark matchups, frozen in a data file so every run is measured on exactly the same games.

data/benchmarks/mirror_benchmark_v1.json holds the 150 matchups alpha 2 was benchmarked on (generated by the
matchup sampler of that time with seed 12345). Changing how training samples
matchups no longer changes the benchmark.
"""

import json
from pathlib import Path

from autogitcg.bridge.initial_equipment import InitialEquipment
from autogitcg.data.deck import Deck
from autogitcg.training.matchup_sampler import Matchup

BENCHMARK_FILE = Path(__file__).resolve().parents[2] / "data" / "benchmarks" / "mirror_benchmark_v1.json"
# 100 blind PvP matchups between held-out tournament decks (scripts/data/lock_tournament_test_set.py), played vs alpha 2.40
TOURNAMENT_BENCHMARK_FILE = BENCHMARK_FILE.with_name("tournament_benchmark_v1.json")
# 100 blind PvP matchups between the most played 6.4+ training tournament decks (scripts/data/lock_meta_test.py)
META_BENCHMARK_FILE = BENCHMARK_FILE.with_name("meta_benchmark_v1.json")


def matchup_to_json(matchup: Matchup) -> dict:
    return {
        "source": matchup.source,
        "decks": [{"characters": list(deck.characters), "cards": list(deck.cards)} for deck in matchup.decks],
        "equipment": [{"who": item.who, "character_index": item.character_index, "definition_id": item.definition_id}
                      for item in matchup.equipment],
        "opponent_deck_known": list(matchup.opponent_deck_known),
        "deck_origins": list(matchup.deck_origins),
    }


def matchup_from_json(entry: dict) -> Matchup:
    return Matchup(
        entry["source"],
        tuple(Deck(characters=deck["characters"], cards=deck["cards"]) for deck in entry["decks"]),
        tuple(InitialEquipment(**item) for item in entry["equipment"]),
        tuple(entry["opponent_deck_known"]),
        tuple(entry["deck_origins"]),
    )


def save_benchmark_matchups(matchups: list[Matchup], path: Path = BENCHMARK_FILE) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps([matchup_to_json(matchup) for matchup in matchups], indent=1))


def load_benchmark_matchups(path: Path = BENCHMARK_FILE) -> list[Matchup]:
    return [matchup_from_json(entry) for entry in json.loads(path.read_text())]
